#!/bin/bash

# Pockets Install Script for macOS
# Installs the addon to every detected WoW AddOns directory:
# Classic Anniversary and the Forever beta. Pass an explicit AddOns path
# as $1 to install to just that one (e.g. TBC or a custom location).

set -e

echo "======================================"
echo "  Pockets Addon Installer (macOS)"
echo "======================================"
echo ""

WOW_PATHS=(
    "/Applications/World of Warcraft/_anniversary_/Interface/AddOns"
    "$HOME/Applications/World of Warcraft/_anniversary_/Interface/AddOns"
    "/Applications/World of Warcraft/_classic_beta_/Interface/Addons"
    "$HOME/Applications/World of Warcraft/_classic_beta_/Interface/Addons"
)

FOUND_PATHS=()
for path in "${WOW_PATHS[@]}"; do
    if [ -d "$path" ]; then
        FOUND_PATHS+=("$path")
    fi
done

if [ -n "$1" ]; then
    if [ ! -d "$1" ]; then
        echo "❌ Error: Specified directory does not exist: $1"
        exit 1
    fi
    INSTALL_DIRS=("$1")
else
    if [ ${#FOUND_PATHS[@]} -eq 0 ]; then
        echo "❌ Error: Could not find a WoW Classic Anniversary or Forever AddOns directory"
        echo ""
        echo "Searched in:"
        for path in "${WOW_PATHS[@]}"; do
            echo "  - $path"
        done
        echo ""
        echo "Please ensure WoW is installed, or specify the path manually:"
        echo "  ./install.sh /path/to/WoW/_anniversary_/Interface/AddOns"
        exit 1
    fi
    INSTALL_DIRS=("${FOUND_PATHS[@]}")
fi

SCRIPT_DIR="$(dirname "$0")"
TOC_FILE="$SCRIPT_DIR/pockets/Pockets.toc"

# Extract version from .toc file
VERSION="unknown"
if [ -f "$TOC_FILE" ]; then
    VERSION=$(grep "^## Version:" "$TOC_FILE" | sed 's/^## Version: *//' | tr -d ' ')
fi

INSTALL_TIMESTAMP=$(date '+%Y-%m-%d %H:%M:%S %Z')

for ADDONS_DIR in "${INSTALL_DIRS[@]}"; do
    TARGET_DIR="$ADDONS_DIR/Pockets"
    echo "Installing to: $ADDONS_DIR"
    echo "Version: $VERSION"
    echo ""

    if [ -d "$TARGET_DIR" ]; then
        echo "Removing existing Pockets installation..."
        rm -rf "$TARGET_DIR"
    fi

    echo "Copying Pockets addon files..."
    mkdir -p "$TARGET_DIR"
    cp -R "$SCRIPT_DIR/pockets/." "$TARGET_DIR/"

    cat > "$TARGET_DIR/.install_info" << EOF
# Pockets Installation Information
# This file is automatically generated by the installer

Version: $VERSION
Installed: $INSTALL_TIMESTAMP
Installer: install.sh
EOF

    if [ -f "$TARGET_DIR/Pockets.toc" ]; then
        echo ""
        echo "✅ Pockets installed successfully!"
        echo "  Version: $VERSION"
        echo "  Installed: $INSTALL_TIMESTAMP"
        echo "  Location: $TARGET_DIR"
        echo ""
    else
        echo "❌ Installation may have failed. Pockets.toc not found in $TARGET_DIR."
        exit 1
    fi
done

echo "Next steps:"
echo "  1. Launch or /reload World of Warcraft"
echo "  2. Type: /pockets help"
echo ""
echo "Testing without in-game actions:"
echo "  /pockets test run   - Run automated tests"
